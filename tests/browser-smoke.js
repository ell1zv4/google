async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const errors = [];
  const closePlayer = async () => {
    await page.locator('#close-player').click();
    await page.waitForFunction(() => document.getElementById('game-root').childElementCount === 0);
  };
  page.on('pageerror', (error) => errors.push(error.message));
  const origin = 'http://127.0.0.1:8767';
  await page.goto(`${origin}/index.html`);
  await page.keyboard.type('risb-local');
  await page.waitForURL('**/search.html');
  await page.locator('#catalog .card').first().waitFor();
  check(await page.locator('#catalog .card').count() === 183, 'Expected 140 games + 43 sites');
  await page.route('**/*', (route) => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  await page.locator('[data-section-link="local"]').first().click();
  check(await page.locator('#catalog .card').count() === 24, 'Expected 24 local games');
  const gameIds = await page.locator('#catalog .card').evaluateAll((cards) => cards.map((card) => card.dataset.id));
  const played = [];
  for (const id of gameIds) {
    await page.locator(`[data-id="${id}"] .card-open`).click();
    check(await page.locator('#player').evaluate((node) => node.open), `Dialog: ${id}`);
    check(await page.locator('#game-root .game-board').count() === 1, `Mount: ${id}`);
    const start = page.locator('#game-root').getByRole('button', { name: 'Empezar', exact: true });
    if (await start.count()) {
      await start.click();
      await page.keyboard.press('ArrowRight');
      await page.keyboard.press('Space');
      await page.waitForTimeout(90);
      await page.locator('#game-root').getByRole('button', { name: 'Reiniciar', exact: true }).click();
      check(await page.locator('#game-root canvas').evaluate((node) => node === document.activeElement), `Restart keyboard focus: ${id}`);
    }
    await page.locator('#restart-game').click();
    check(await page.locator('#game-root .game-board').count() === 1, `Restart: ${id}`);
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => document.getElementById('game-root').childElementCount === 0);
    check(!await page.locator('#player').evaluate((node) => node.open), `Escape: ${id}`);
    check(await page.locator('#game-root').evaluate((node) => node.childElementCount) === 0, `Cleanup: ${id}`);
    check(await page.locator(`[data-id="${id}"] .card-open`).evaluate((node) => node === document.activeElement), `Return focus: ${id}`);
    played.push(id);
  }
  await page.locator('[data-id="tictactoe"] .card-open').click();
  for (const index of [0, 3, 1, 4, 2]) await page.locator('#game-root .board-cell').nth(index).click();
  check((await page.locator('.game-status').innerText()).includes('Gana X'), 'Tic tac toe winner');
  await closePlayer();
  await page.locator('[data-id="connect4"] .card-open').click();
  for (const index of [0, 1, 0, 1, 0, 1, 0]) await page.locator('#game-root .board-cell').nth(index).click();
  check((await page.locator('.game-status').innerText()).includes('Gana X'), 'Connect four winner');
  await closePlayer();
  await page.locator('[data-id="2048"] .card-open').click();
  check(await page.locator('#game-root').evaluate((node) => node === document.activeElement), '2048 receives keyboard focus');
  await page.keyboard.press('ArrowLeft');
  await page.locator('#fullscreen').click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  check(await page.evaluate(() => Boolean(document.fullscreenElement)), 'Fullscreen enters');
  await page.locator('#fullscreen').click();
  await page.waitForFunction(() => !document.fullscreenElement);
  check(!await page.evaluate(() => Boolean(document.fullscreenElement)), 'Fullscreen exits');
  await closePlayer();
  if (await page.locator('#favorite-snake').getAttribute('aria-pressed') !== 'true') await page.locator('#favorite-snake').click();
  check(await page.locator('#favorite-snake').getAttribute('aria-pressed') === 'true', 'Favorite saved');
  await page.reload();
  await page.locator('#favorite-snake').waitFor();
  check(await page.locator('#favorite-snake').getAttribute('aria-pressed') === 'true', 'Favorite persists');
  await page.locator('#search').fill('sin-coincidencia-12345');
  check(await page.locator('#empty-state').isVisible(), 'Empty state');
  await page.locator('#clear-search').click();
  await page.locator('[data-section-link="football"]').click();
  check(await page.locator('#catalog .card').count() === 8, 'Football links');
  check(await page.locator('#catalog .card-open[target="_blank"]').count() === 8, 'Official sites open in new tabs');
  await page.locator('[data-section-link="games"]').click();
  await page.locator('[data-id="external-001"] .card-open').click();
  check(await page.locator('#game-root iframe').count() === 1, 'External iframe opens');
  await closePlayer();
  check(await page.locator('#game-root iframe').count() === 0, 'External iframe removed');
  await page.locator('[data-section-link="recent"]').click();
  check(await page.locator('#catalog .card').count() >= 24, 'Recent games recorded');
  await page.locator('#clear-history').click();
  check(await page.locator('#empty-state').isVisible(), 'Recent list cleared');
  await page.locator('[data-section-link="home"]').click();
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No mobile horizontal overflow');
  await page.screenshot({ path: 'output/playwright/risb-mobile.png' });
  await page.locator('[data-section-link="local"]').first().click();
  await page.locator('[data-id="minesweeper"] .card-open').click();
  await page.locator('#game-root .board-cell').first().click();
  check(!(await page.locator('.game-status').innerText()).includes('mina. Has perdido'), 'First minesweeper move is safe');
  check(await page.locator('#player').evaluate((node) => node.scrollWidth <= node.clientWidth), 'Mobile game fits dialog');
  await page.screenshot({ path: 'output/playwright/risb-mobile-game.png' });
  await closePlayer();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('[data-section-link="home"]').click();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: 'output/playwright/risb-desktop.png' });
  check(errors.length === 0, `Browser errors: ${errors.join('; ')}`);
  return { gamesOpenedRestartedClosed: played, externalRequestsBlocked: true, favoritesPersist: true, desktopAndMobile: true, browserErrors: errors };
}
